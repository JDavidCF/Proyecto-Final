export const messages: Record<Locale, Messages> = Object.fromEntries(
  LANGUAGES.map(({ code }) => [code, code === 'es-CO' ? {
    ...es,
    ...voiceCatalogs[code],
  } : {
    ...es,
    ...catalogs[code],
    ...moreCatalogs[code],
    ...additionalCatalogs[code],
    ...uiCatalogs[code],
    ...fieldCatalogs[code],
    ...landingCatalogs[code],
    ...interfaceCatalogs[code],
    ...authCatalogs[code],
    ...voiceCatalogs[code],
  }])
) as Record<Locale, Messages>;

function detectLocale(): Locale {
  const saved = localStorage.getItem('stocknova_locale');
  if (LANGUAGES.some(({ code }) => code === saved)) return saved as Locale;
  const assistantLocale = localStorage.getItem('stocknova_assistant_language');
  if (LANGUAGES.some(({ code }) => code === assistantLocale)) return assistantLocale as Locale;
  const browserLocales = navigator.languages?.length
    ? navigator.languages
    : [navigator.language ?? 'es-CO'];
  for (const browserLocale of browserLocales) {
    const normalized = browserLocale.toLowerCase();
    if (normalized.startsWith('es')) return 'es-CO';
    if (normalized.startsWith('pt')) return 'pt-BR';
    if (normalized.startsWith('zh')) return 'zh-CN';
    const match = LANGUAGES.find(({ code }) => code.toLowerCase() === normalized.split('-')[0]);
    if (match) return match.code;
  }
  return 'es-CO';
}

interface LanguageContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string) => string;
}

const defaultValue: LanguageContextValue = {
  locale: 'es-CO',
  setLocale: () => undefined,
  t: (key) => key,
};
const LanguageContext = createContext<LanguageContextValue>(defaultValue);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(detectLocale);
  const setLocale = (next: Locale) => setLocaleState(next);

  useEffect(() => {
    localStorage.setItem('stocknova_locale', locale);
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === 'ar' ? 'rtl' : 'ltr';
    document.title = messages[locale]['StockNova — Sistema de Gestión y Control de Inventarios'];
  }, [locale]);

  const value = useMemo<LanguageContextValue>(() => ({
    locale,
    setLocale,
    t: (key) => messages[locale][key] ?? messages['es-CO'][key] ?? key,
  }), [locale]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext);
}
